"""Build self-contained lab versions of every hunt query.

Each lab file shadows the real tables with `let <Table> = datatable(...)` built from the
synthetic JSON in samples/, and pins `now()` to the lab anchor time. Paste a lab file into
any Kusto query window (a free Azure Data Explorer cluster works) and it runs with no tenant.

Usage:
    python tools/build_labs.py           # write labs/
    python tools/build_labs.py --check   # exit 1 if labs/ is stale (used in CI)
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
QUERIES, SAMPLES, LABS = ROOT / "queries", ROOT / "samples", ROOT / "labs"
LAB_NOW = "datetime(2026-03-11T00:00:00Z)"


def kql_literal(value, kind: str) -> str:
    if kind == "datetime":
        return f"datetime({value})"
    if kind == "dynamic":
        return f"dynamic({json.dumps(value, separators=(',', ':'))})"
    if kind in ("int", "long", "real"):
        return str(value)
    if kind == "bool":
        return "true" if value else "false"
    # JSON string escaping (\" and \\) is valid KQL string-literal escaping for ASCII data
    return json.dumps(str(value), ensure_ascii=True)


def datatable(table: str, schema: dict, rows: list[dict]) -> str:
    cols = schema[table]
    header = ", ".join(f"{c}:{t}" for c, t in cols)
    body = ",\n    ".join(", ".join(kql_literal(r[c], t) for c, t in cols) for r in rows)
    return f"let {table} = datatable({header}) [\n    {body}\n];"


def tables_used(query: str, schema: dict) -> list[str]:
    return [t for t in schema if re.search(rf"\b{t}\b", query)]


def build_lab(query_path: Path, schema: dict) -> str:
    text = query_path.read_text(encoding="utf-8")
    header = [ln for ln in text.splitlines() if ln.startswith("//")]
    body = "\n".join(ln for ln in text.splitlines() if not ln.startswith("//")).strip()
    lets = [datatable(t, schema, json.loads((SAMPLES / f"{t}.json").read_text()))
            for t in tables_used(body, schema)]
    body = body.replace("now()", LAB_NOW)
    return "\n".join([
        f"// LAB VERSION of queries/{query_path.name}. Generated by tools/build_labs.py; do not edit.",
        f"// Synthetic data only. now() is pinned to {LAB_NOW}.",
        *header, "", *lets, "", body, "",
    ])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    schema = json.loads((SAMPLES / "schema.json").read_text())
    LABS.mkdir(exist_ok=True)
    stale = []
    for q in sorted(QUERIES.glob("*.kql")):
        lab = build_lab(q, schema)
        dest = LABS / q.name
        if args.check:
            if not dest.exists() or dest.read_text(encoding="utf-8") != lab:
                stale.append(dest.name)
        else:
            dest.write_text(lab, encoding="utf-8")
    if stale:
        print("stale lab files (run python tools/build_labs.py):", ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
